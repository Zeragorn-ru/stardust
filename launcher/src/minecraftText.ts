/**
 * Приводит текст бейджа к отдельным глифам, которые есть в шрифте Minecraft.
 * Mojangles рисует такие символы как обычный текст: селектор emoji-представления
 * (U+FE0F) и модификаторы тона кожи в нём не используются и мешают подстановке
 * пиксельного глифа. Символы, которых в шрифте нет, остаются как есть — их
 * отрисует резервный шрифт.
 */
export function normalizeMinecraftText(value: string): string {
  return value.replace(/️/g, "").replace(/[\u{1F3FB}-\u{1F3FF}]/gu, "");
}
