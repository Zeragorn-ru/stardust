// Обработка «протухших» чанков при деплое.
//
// Vite кладёт в имя каждого чанка хэш контента. Пока открыта вкладка,
// деплой может заменить ассеты на сервере — и догрузка ленивого чанка
// (например, 3D-просмотра скинов) упадёт: браузер получил не модуль, а
// 404/HTML-фоллбэк. React Router ловит это как Unexpected Application
// Error и рисует красный экран.
//
// vite:preloadError — стандартное событие Vite: возбуждается при ошибке
// динамического import(). Причина почти всегда одна: приложение на
// сервере новее, чем вкладка. Перегружаем страницу целиком (SPA поднимет
// свежие чанки), а не молчим. Цикл невозможен: после перезагрузки
// загруженный index.html ссылается на существующие чанки.
export function reloadOnStaleChunk(): void {
  window.addEventListener("vite:preloadError", (event) => {
    // Если кто-то уже показал свою обработку — не мешаем.
    if (event.defaultPrevented) return;
    // Не даём всплыть в ErrorBoundary экраном ошибки.
    event.preventDefault();
    window.location.reload();
  });
}
